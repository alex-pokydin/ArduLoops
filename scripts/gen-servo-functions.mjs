// Builds src/lib/servoFunctionData.ts from ArduPilot's SERVOn_FUNCTION value list.
// Usage: node scripts/gen-servo-functions.mjs [path/to/ardupilot]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ardupilot = resolve(process.argv[2] ?? join(root, "..", "ardupilot"));
const src = readFileSync(join(ardupilot, "libraries", "SRV_Channel", "SRV_Channel.cpp"), "utf8");

const start = src.indexOf("// @Param: FUNCTION");
const end = src.indexOf("AP_GROUPINFO", start);
if (start < 0 || end < 0) throw new Error("SERVOn_FUNCTION block not found");
const block = src.slice(start, end);

// Vehicle-tagged lines say which firmware has the value: "// @Values{Plane, Copter}: 2:Flap,3:FlapAuto"
const lists = { copter: new Map(), plane: new Map() };
for (const m of block.matchAll(/\/\/ @Values\{([^}]*)\}:\s*(.*)/g)) {
  const vehicles = m[1].split(",").map((v) => v.trim().toLowerCase());
  for (const item of m[2].split(",")) {
    const [num, ...rest] = item.split(":");
    const value = Number(num.trim());
    const name = rest.join(":").trim();
    if (!Number.isFinite(value) || !name) continue;
    for (const v of vehicles) lists[v]?.set(value, name);
  }
}

const dump = (map) => [...map.entries()].sort((a, b) => a[0] - b[0]).map(([v, n]) => `  [${v}, ${JSON.stringify(n)}],`).join("\n");
const out = `// Generated by scripts/gen-servo-functions.mjs from ArduPilot SRV_Channel.cpp (SERVOn_FUNCTION @Values). Do not edit.

export const COPTER_FUNCTIONS: [number, string][] = [
${dump(lists.copter)}
];

export const PLANE_FUNCTIONS: [number, string][] = [
${dump(lists.plane)}
];
`;
writeFileSync(join(root, "src", "lib", "servoFunctionData.ts"), out);
console.log(`copter ${lists.copter.size}, plane ${lists.plane.size}`);
